#!/usr/bin/env python3
"""Translates W3CRNC of model/src/ww3_trnc.F90 (the pinned WW3) into Rust, statement by statement: the dimensions, variables and
attributes of one track file, in the Fortran's order of calls. Usage: trnc_crnc_gen.py [--check]. Without --check it writes
rust/tools/ww3_trnc/src/crnc.rs; with --check it exits 1 when that file differs from a fresh run."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "WW3/model/src/ww3_trnc.F90"
OUT = ROOT / "rust/tools/ww3_trnc/src/crnc.rs"
TYPES = {"NF90_DOUBLE": "NC_DOUBLE", "NF90_FLOAT": "NC_FLOAT", "NF90_INT": "NC_INT", "NF90_CHAR": "NC_CHAR"}


def statements():
    text = SRC.read_text().split("\n")
    a = next(i for i, l in enumerate(text) if re.match(r"\s*SUBROUTINE W3CRNC", l))
    b = next(i for i, l in enumerate(text) if re.match(r"\s*END SUBROUTINE W3CRNC", l))
    out, buf, first = [], "", a + 1
    for no, raw in enumerate(text[a + 1:b], a + 2):
        s = raw.split("!")[0].strip() if "'" not in raw.split("!")[0] or raw.count("!") == 0 else raw.strip()
        if not s:
            continue
        if not buf:
            first = no
        buf += s
        if buf.endswith("&"):
            buf = buf[:-1].rstrip() + " "
            continue
        out.append((first, buf))
        buf = ""
    return b - a + 1, a + 1, out


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines, first, st = statements()
    o = ["// SPDX-License-Identifier: MPL-2.0",
         f"//! W3CRNC of `model/src/ww3_trnc.F90:{first}-{first + lines - 1}`: the NetCDF dimensions, variables and attributes of one track file, in the",
         "//! Fortran's order of calls. Generated by `scripts/trnc_crnc_gen.py` (`--check` finds it stale); do not edit.",
         "", "use crate::nc::{self, DEFLATE, FILL_FLOAT, FILL_INT};", "",
         "/// Returns `NCID` and `VARID(1:18)`, index 0 unused. `ck` is `CHECK_ERR`, and `dimln` is `DIMLN(1:4)` from index 1.",
         "#[allow(unused_assignments, clippy::too_many_lines)]",
         "pub fn w3crnc(nctype: i32, ncfile: &str, dimln: [usize; 5], flagll: bool, caltype: &str, ck: &mut dyn FnMut(i32)) -> (i32, [i32; 19]) {",
         "    let (mut ncid, mut dimid, mut varid) = (0, [0i32; 5], [0i32; 19]);", "    let mut iret = 0;"]
    ind = 1
    arm = False
    pad = lambda: "    " * ind
    for no, s in st:
        if re.match(r"(USE |IMPLICIT|INTEGER|CHARACTER)", s):
            continue
        if s == "RETURN":
            continue
        m = re.match(r"IF ?\(NCTYPE\.EQ\.(\d)\) +IRET ?= ?(.*)$", s)
        guard = m.group(1) if m else None
        body = m.group(2) if m else re.sub(r"^IRET ?= ?", "", s)
        if s == "IF (FLAGLL) THEN":
            o.append(pad() + "if flagll {"); ind += 1; continue
        if s == "ELSE":
            ind -= 1; o.append(pad() + "} else {"); ind += 1; continue
        if s == "END IF":
            ind -= 1; o.append(pad() + "}"); continue
        if s.startswith("SELECT CASE"):
            o.append(pad() + "match caltype.trim_end() {"); ind += 1; continue
        if s == "END SELECT":
            o.append(pad() + "_ => {}"); ind -= 1; o.append(pad() + "}"); continue
        m = re.match(r"CASE \('(.*)'\)", s)
        if m:
            o.append(pad() + f'"{m.group(1)}" => {{'); arm = True; ind += 1; continue
        if s == "CALL CHECK_ERR(IRET)":
            o.append(pad() + "ck(iret);"); continue
        m = re.match(r"NF90_DEF_DIM\(NCID, '(\w+)', DIMLN\((\d)\), DIMID\((\d)\)\)", body)
        if m:
            o.append(pad() + f'iret = nc::def_dim(ncid, "{m.group(1)}", dimln[{m.group(2)}], &mut dimid[{m.group(3)}]);'); continue
        m = re.match(r"NF90_DEF_VAR\(NCID, ?'(\w+)', ?(NF90_\w+), ?\(/(.*)/\), ?VARID\((\d+)\)\)", body)
        if m:
            d = ", ".join(f"dimid[{x}]" for x in re.findall(r"DIMID\((\d)\)", m.group(3)))
            o.append(pad() + f'iret = nc::def_var(ncid, "{m.group(1)}", nc::{TYPES[m.group(2)]}, &[{d}], &mut varid[{m.group(4)}]);'); continue
        m = re.match(r"NF90_DEF_VAR_DEFLATE\(NCID, VARID\((\d+)\), 1, 1, DEFLATE\)", body)
        if m:
            o.append(pad() + f"if nctype == {guard} {{"); o.append(pad() + f"    iret = nc::def_var_deflate(ncid, varid[{m.group(1)}], 1, 1, DEFLATE);"); o.append(pad() + "}"); continue
        m = re.match(r"NF90_CREATE\(TRIM\(NCFILE\), (\w+), NCID\)", body)
        if m:
            mode = "0" if m.group(1) == "NF90_CLOBBER" else "nc::NC_NETCDF4"
            o.append(pad() + f"if nctype == {guard} {{"); o.append(pad() + f"    iret = nc::create(ncfile, {mode}, &mut ncid);"); o.append(pad() + "}"); continue
        m = re.match(r"NF90_PUT_ATT\(NCID, ?VARID\((\d+)\), ?'(\w+)', ?(.*)\)$", body)
        if m:
            v, name, val = m.groups()
            val = val.strip()
            if val == "TRIM(CALTYPE)":
                call = f'nc::put_att_text(ncid, varid[{v}], "{name}", caltype.trim_end())'
            elif val == "NF90_FILL_FLOAT":
                call = f'nc::put_att_float(ncid, varid[{v}], "{name}", FILL_FLOAT)'
            elif val == "NF90_FILL_INT":
                call = f'nc::put_att_int(ncid, varid[{v}], "{name}", FILL_INT)'
            elif val.startswith("'"):
                call = f'nc::put_att_text(ncid, varid[{v}], "{name}", {rust_str(val[1:-1])})'
            elif re.fullmatch(r"-?\d+\.\d*(E[-+]?\d+)?", val):
                call = f'nc::put_att_float(ncid, varid[{v}], "{name}", {val}0_f32)' if val.endswith(".") else f'nc::put_att_float(ncid, varid[{v}], "{name}", {val}_f32)'
            elif re.fullmatch(r"-?\d+", val):
                call = f'nc::put_att_int(ncid, varid[{v}], "{name}", {val})'
            else:
                raise SystemExit(f"{no}: attribute value {val!r}")
            o.append(pad() + f"iret = {call};")
            if arm:
                ind -= 1; o.append(pad() + "}"); arm = False
            continue
        raise SystemExit(f"{no}: statement {s!r} is not one the generator knows")
    o += ["    (ncid, varid)", "}", ""]
    text = "\n".join(o)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)


main()
